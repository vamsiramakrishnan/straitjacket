# --------------------------------------------------- (c) declared census cap
def test_census_unfittable_escalates_to_flood(tmp_path, real_outputs):
    """v2 semantics (EDC §13): a budget that cannot fit the identity
    census escalates to FLOOD — first-N stable census, exact declared
    omission, and the complete census behind a content-addressed blob —
    instead of v1's identity-dropping '+N more failures' cut."""
    from ctx.digest.pytestprof import PytestProfile

    body = PytestProfile().render(
        _ctx_for(tmp_path, real_outputs["fail_q"], result_tokens=60)
    )
    assert "· flood ·" in body
    assert "failure classes:" in body  # class histogram (census-of-census)
    rows = CENSUS_ROW_RE.findall(body)
    assert 1 <= len(rows) < 8  # capped, never empty
    m = re.search(r"… \+(\d+) more identities · full census blob:([0-9a-f]{12})$", body, re.M)
    assert m, body
    assert len(rows) + int(m.group(1)) == 8  # omission is exact


# ------------------------------------------------------------ (d) dense mode
def test_dense_mode_inlines_per_test_error_lines(tmp_path, real_outputs):
    from ctx.digest.pytestprof import PytestProfile

    plain = PytestProfile().render(_ctx_for(tmp_path, real_outputs["fail_q"]))
    dense = PytestProfile().render(_ctx_for(tmp_path, real_outputs["fail_q"], dense=True))

    # Each census row gains its own assertion/exception evidence line(s).
    assert "ValueError: beta exploded" in dense
    # v2: one-liners are default, so the class-deduped summary rides in the
    # plain census too — but the raw E-line evidence stays dense-only.
    assert "beta exploded" in plain
    assert "ValueError: beta exploded" not in plain
    err_lines = re.findall(r"^\s+E\b.*$", dense, re.M)
    assert len(err_lines) >= 8  # at least one expanded evidence line per row
    # Dense mode stays budget-bounded: unfittable census → declared FLOOD.
    squeezed = PytestProfile().render(
        _ctx_for(tmp_path, real_outputs["fail_q"], result_tokens=60, dense=True)
    )
    assert re.search(r"… \+\d+ more identities", squeezed)


# ------------------------------------------------------- (e) spans resolve
def test_census_spans_resolve_to_traceback_blocks(state_home, workspace_dir, real_outputs):
    from ctx.retrieval import Selector, get

    ws = make_ws(workspace_dir)
    store = make_store(ws)
    digest, m = _digest_for(ws, store, real_outputs["fail_q"])
    short = str(m["id"]).removeprefix("sha256:")[:12]

    row = re.search(
        r"^  \d+\. test_seed\.py::test_gamma  \S+ · \S+ · .*? · "
        r"stdout:L(\d+)-L(\d+) · span ([0-9a-f]{10})$",
        digest, re.M,
    )
    assert row, digest
    a, b, sid = int(row.group(1)), int(row.group(2)), row.group(3)
    span = store.get_span(sid)
    assert span["kind"] == "region" and span["a"] == a and span["b"] == b
    out = get(store, ws, f"run:{short}#stdout", Selector(span=sid))
    assert "test_gamma" in out  # the block's own header
    assert 'assert "needle" in "haystack"' in out  # the actual traceback evidence


