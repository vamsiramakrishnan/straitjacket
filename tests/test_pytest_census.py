# --------------------------------------------- (g) truncated output degrades
def test_truncated_piped_output_degrades_to_partial_census(tmp_path, real_outputs):
    from ctx.digest.pytestprof import PytestProfile

    head = "\n".join(real_outputs["fail_q"].splitlines()[:20]) + "\n"
    prof = PytestProfile()
    ctx = _ctx_for(tmp_path, head, argv=("bash",))  # argv gives no pytest hint
    assert prof.detect(ctx)  # FAILURES section shape still detected
    body = prof.render(ctx)
    assert "summary line not found" in body  # declared degradation, kept
    rows = CENSUS_ROW_RE.findall(body)
    assert rows, body  # census of whatever parsed
    assert rows[0][0] == "TestBox.test_edge"  # header name: no summary section survived
    # v2 honesty: a truncated parse is never attested complete.
    assert "completeness unattested" in body


def test_truncated_verbose_output_uses_progress_rows(tmp_path, real_outputs):
    """-v output cut before the FAILURES section: the census degrades to the
    per-test FAILED progress rows, each with its own line coordinate."""
    from ctx.digest.pytestprof import PytestProfile

    lines = real_outputs["fail_v"].splitlines()
    cut = next(i for i, ln in enumerate(lines) if "FAILURES" in ln)
    head = "\n".join(lines[:cut]) + "\n"
    body = PytestProfile().render(_ctx_for(tmp_path, head))
    rows = CENSUS_ROW_RE.findall(body)
    assert [r[0] for r in rows] == FAIL_IDS  # all 8 from progress rows
    assert all(r[4] == "" for r in rows)  # single-line coordinates, no fake blocks
    assert all(r[2] == "?" for r in rows)  # class honestly unknown, never invented
    assert "summary line not found" in body


